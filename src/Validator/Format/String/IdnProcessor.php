    public function __construct(
        private readonly PregExecutor $pregExecutor = new PregExecutor(),
    ) {}

    public function isAsciiHostname(string $domain): bool
    {
        if (1 === $this->pregExecutor->match(self::CONTROL_CHARACTER_PATTERN, $domain)) {
            return false;
        }

        if (1 !== $this->pregExecutor->match(self::ASCII_PRINTABLE_PATTERN, $domain)) {
            return false;
        }

        $labels = $this->extractLabels($domain);

        if (false === $labels) {
            return false;
        }

        foreach ($labels as $label) {
            if (1 !== $this->pregExecutor->match(self::LDH_LABEL_PATTERN, $label)) {
                return false;
            }

            if (1 === $this->pregExecutor->match(self::ALABEL_PREFIX_PATTERN, $label)
                && false === $this->verifyAlabel($label)) {
                return false;
            }
        }

        return strlen($domain) <= self::MAX_DOMAIN_LENGTH;
    }

    public function isInternationalizedHostname(string $domain): bool
    {
        if (1 === $this->pregExecutor->match(self::CONTROL_CHARACTER_PATTERN, $domain)) {
            return false;
        }

        $labels = $this->extractLabels($domain);

        if (false === $labels) {
            return false;
        }

        foreach ($labels as $label) {
            if (false === $this->verifyLabel($label)) {
                return false;
            }
        }

        if (false === $this->isIntlAvailable()) {
            foreach ($labels as $label) {
                if (1 !== $this->pregExecutor->match(self::ASCII_PRINTABLE_PATTERN, $label)) {
                    return false;
                }
            }

            return strlen($domain) <= self::MAX_DOMAIN_LENGTH;
        }

        return $this->isMappedDomainNameValid($domain);
    }

    private function verifyLabel(string $label): bool
    {
        if (1 === $this->pregExecutor->match(self::ASCII_PRINTABLE_PATTERN, $label)) {
            if (1 !== $this->pregExecutor->match(self::LDH_LABEL_PATTERN, $label)) {
                return false;
            }

            if (1 === $this->pregExecutor->match(self::ALABEL_PREFIX_PATTERN, $label)
                && false === $this->verifyAlabel($label)) {
                return false;
            }

            return true;
        }

        if (true === $this->hasRfc5892DisallowedCodePoint($label)) {
            return false;
        }

        return $this->passesContextoRules($label);
    }

    /**
     * @return list<string>|false
     */
    private function extractLabels(string $domain): array|false
    {
        try {
            $labels = $this->pregExecutor->split(self::LABEL_SEPARATOR_PATTERN, $domain);
        } catch (PregRuntimeException) {
            return false;
        }

        if (false === is_array($labels)) {
            return false;
        }

        foreach ($labels as $label) {
            if ('' === $label) {
                return false;
            }
        }

        return $labels;
    }

    private function verifyAlabel(string $label): bool
    {
        $decoded = $this->toUnicode($label);

        if (false === $decoded || '' === $decoded) {
            return false;
        }

        if (false === $this->isRfc5892LabelPermitted($decoded)) {
            return false;
        }

        if (false === $this->passesContextoRules($decoded)) {
            return false;
        }

        $encoded = $this->toAscii($decoded);

        if (false === $encoded || '' === $encoded) {
            return false;
        }

        return strtolower($encoded) === strtolower($label);
    }

    private function isMappedDomainNameValid(string $domain): bool
    {
        if ('' === $domain) {
            return false;
        }

        $info = [];
        $ascii = idn_to_ascii($domain, $this->asciiIdnaFlags(), INTL_IDNA_VARIANT_UTS46, $info);

        if (false === $ascii) {
            return false;
        }

        return 0 === ($info['errors'] ?? -1);
    }

    private function isRfc5892LabelPermitted(string $label): bool
    {
        foreach (mb_str_split($label) as $character) {
            $codePoint = (int) mb_ord($character, 'UTF-8');

            if (self::ZERO_WIDTH_NON_JOINER === $codePoint || self::ZERO_WIDTH_JOINER === $codePoint) {
                continue;
            }

            if (false === $this->isPvalidCodePoint($codePoint)
                && false === $this->isContextoCodePoint($codePoint)) {
                return false;
            }
        }

        return true;
    }

    private function hasRfc5892DisallowedCodePoint(string $label): bool
    {
        if (1 === $this->pregExecutor->match(self::HANGUL_TONE_MARK_PATTERN, $label)
            || 1 === $this->pregExecutor->match(self::VERTICAL_KANA_REPEAT_PATTERN, $label)) {
            return true;
        }

        foreach ([self::TATWEEL, self::NKO_LAJANYALAN, self::VERTICAL_IDEOGRAPHIC_ITERATION_MARK] as $codePoint) {
            $character = mb_chr($codePoint, 'UTF-8');

            if (false === $character) {
                return false;
            }

            if (str_contains($label, $character)) {
                return true;
            }
        }

        return false;
    }

    private function passesContextoRules(string $label): bool
    {
        $characters = mb_str_split($label);

        foreach ($characters as $index => $character) {
            $codePoint = (int) mb_ord($character, 'UTF-8');

            if (false === $this->isContextoCodePoint($codePoint)) {
                continue;
            }

            $previous = $index > 0 ? $characters[$index - 1] : null;
            $next = $index + 1 < count($characters) ? $characters[$index + 1] : null;

            if (false === $this->passesContextoRule($codePoint, $label, $previous, $next)) {
                return false;
            }
        }

        return true;
    }

    private function passesContextoRule(int $codePoint, string $label, ?string $previous, ?string $next): bool
    {
        return match (true) {
            self::MIDDLE_DOT === $codePoint => 'l' === $previous && 'l' === $next,
            self::GREEK_KERAIA === $codePoint => null !== $next
                && 1 === $this->pregExecutor->match(self::GREEK_FOLLOWER_PATTERN, $next),
            self::HEBREW_GERESH === $codePoint, self::HEBREW_GERSHAYIM === $codePoint => null !== $previous
                && 1 === $this->pregExecutor->match(self::HEBREW_LETTER_PATTERN, $previous),
            self::KATAKANA_MIDDLE_DOT === $codePoint => 1 === $this->pregExecutor->match(
                self::KATAKANA_MIDDLE_DOT_CONTEXT_PATTERN,
                $label,
            ),
            $codePoint >= 0x0660 && $codePoint <= 0x0669 => 1 !== $this->pregExecutor->match(
                self::EXTENDED_ARABIC_INDIC_DIGIT_PATTERN,
                $label,
            ),
            default => 1 !== $this->pregExecutor->match(self::ARABIC_INDIC_DIGIT_PATTERN, $label),
        };
    }

    private function isContextoCodePoint(int $codePoint): bool
    {
        return self::MIDDLE_DOT === $codePoint
            || self::GREEK_KERAIA === $codePoint
            || self::HEBREW_GERESH === $codePoint
            || self::HEBREW_GERSHAYIM === $codePoint
            || self::KATAKANA_MIDDLE_DOT === $codePoint
            || ($codePoint >= 0x0660 && $codePoint <= 0x0669)
            || ($codePoint >= 0x06F0 && $codePoint <= 0x06F9);
    }

    private function isPvalidCodePoint(int $codePoint): bool
    {
        $low = 0;
        $high = intdiv(count(self::PVALID_RANGES), 2) - 1;

        while ($low <= $high) {
            $middle = intdiv($low + $high, 2);
            $rangeStart = self::PVALID_RANGES[$middle * 2];
            $rangeEnd = self::PVALID_RANGES[$middle * 2 + 1];

            if ($codePoint < $rangeStart) {
                $high = $middle - 1;
            } elseif ($codePoint > $rangeEnd) {
                $low = $middle + 1;
            } else {
                return true;
            }
        }

        return false;
    }

    private function isIntlAvailable(): bool
    {
        return function_exists('idn_to_ascii') && function_exists('idn_to_utf8');
    }

    private function toAscii(string $domain): string|false
    {
        if (false === $this->isIntlAvailable() || '' === $domain) {
            return false;
        }

        $info = [];
        $ascii = idn_to_ascii($domain, $this->asciiIdnaFlags(), INTL_IDNA_VARIANT_UTS46, $info);

        if (false === $ascii || 0 !== ($info['errors'] ?? -1)) {
            return false;
        }

        return $ascii;
    }

    private function asciiIdnaFlags(): int
    {
        return IDNA_NONTRANSITIONAL_TO_ASCII | IDNA_CHECK_BIDI | IDNA_CHECK_CONTEXTJ;
    }

    private function unicodeIdnaFlags(): int
    {
        return IDNA_NONTRANSITIONAL_TO_UNICODE | IDNA_CHECK_BIDI | IDNA_CHECK_CONTEXTJ;
    }

    private function toUnicode(string $label): string|false
    {
        if (false === $this->isIntlAvailable() || '' === $label) {
            return false;
        }

        return idn_to_utf8($label, $this->unicodeIdnaFlags(), INTL_IDNA_VARIANT_UTS46);
    }
